test("HTTP manual → checkout idempotente → recuperación e historial comercial con permisos", async () => {
  const first = await cart(); await addItems(first.cookie);
  const invalid = await request("/api/store/cart/prescription/manual", { cookie: first.cookie, method: "PUT", body: { ...prescription, rightEye: { ...prescription.rightEye, axis: 181 } } });
  assert.equal(invalid.status, 400);
  const saved = await data(await request("/api/store/cart/prescription/manual", { cookie: first.cookie, method: "PUT", body: prescription }));
  const recipeId = saved.externalPrescription.id;
  const edited = { ...prescription, fulfillmentNotes: "Receta corregida antes de comprar" };
  const updated = await data(await request("/api/store/cart/prescription/manual", { cookie: first.cookie, method: "PUT", body: edited }));
  assert.equal(updated.externalPrescription.id, recipeId);
  assert.equal(await db.external_prescriptions.count({ where: { cart_id: first.cart.id } }), 1);
  assert.deepEqual((await data(await request("/api/store/cart", { cookie: first.cookie }))).externalPrescription.confirmedData, edited);
  await configure(first.cookie);
  const order = await data(await request("/api/store/cart/checkout", { cookie: first.cookie, method: "POST" }), 201);
  assert.equal(order.order.externalPrescription.id, recipeId);
  const retry = await data(await request("/api/store/cart/checkout", { cookie: first.cookie, method: "POST" }), 201);
  assert.equal(retry.order.id, order.order.id);
  const endpoint = `/api/store/orders/${order.order.id}/prescription`;
  const response = await request(endpoint, { cookie: first.cookie });
  assert.match(response.headers.get("cache-control"), /private, no-store/);
  assert.deepEqual((await data(response)).confirmedData, edited);
  assert.equal((await request(endpoint)).status, 404);
  assert.equal((await request(endpoint, { cookie: (await cart()).cookie })).status, 404);
  assert.equal((await request(`/api/external-prescriptions/${recipeId}`)).status, 401);
  const denied = await login(true);
  assert.equal((await request(`/api/external-prescriptions/${recipeId}`, { cookie: denied })).status, 403);
  const admin = await login();
  assert.deepEqual((await data(await request(`/api/external-prescriptions/${recipeId}`, { cookie: admin }))).confirmedData, edited);
  // El tablero solicita columnas y receta en paralelo con la misma sesión.
  const simultaneous = await Promise.all(Array.from({ length: 12 }, () => request(`/api/external-prescriptions/${recipeId}`, { cookie: admin })));
  assert.deepEqual(simultaneous.map((response) => response.status), Array(12).fill(200));
  const second = await cart(); await addItems(second.cookie);
  const newer = await data(await request("/api/store/cart/prescription/manual", { cookie: second.cookie, method: "PUT", body: prescription }));
  assert.notEqual(newer.externalPrescription.id, recipeId);
  await configure(second.cookie); await data(await request("/api/store/cart/checkout", { cookie: second.cookie, method: "POST" }), 201);
  assert.deepEqual((await db.external_prescriptions.findUniqueOrThrow({ where: { id: recipeId } })).confirmed_data, edited);
  const history = await data(await request(`/api/external-prescriptions?customerId=${order.order.customer.id}`, { cookie: admin }));
  assert.equal(history.length, 2);
  assert.equal((await request("/api/store/cart/prescription/image", { cookie: first.cookie, method: "DELETE" })).status, 409);
  await db.user_sessions.updateMany({ where: { token_hash: hashSessionToken(admin.split("=")[1]) }, data: { revoked_at: new Date() } });
  assert.equal((await request(`/api/external-prescriptions/${recipeId}`, { cookie: admin })).status, 401);
});

test("Un carrito invitado comprado tras registrarse queda en los pedidos de su cuenta", async () => {
  const guest = await cart(); await addItems(guest.cookie);
  await data(await request("/api/store/cart/prescription/manual", { cookie: guest.cookie, method: "PUT", body: prescription }));
  const customer = { ...buyer, rut: fixtureRut(9302), email: "receta-cuenta@example.invalid", password: "Prueba-cuenta-recetas-2026!" };
  const registration = await request("/api/store/accounts/register", { cookie: guest.cookie, method: "POST", body: customer });
  const account = await data(registration, 201);
  const cookie = `${guest.cookie}; ${registration.headers.getSetCookie()[0].split(";")[0]}`;
  await configure(cookie, customer);
  const checked = await data(await request("/api/store/cart/checkout", { cookie, method: "POST" }), 201);
  assert.equal((await db.store_carts.findUniqueOrThrow({ where: { id: guest.cart.id } })).customer_account_id, account.account.id);
  const accountCookie = registration.headers.getSetCookie()[0].split(";")[0];
  assert.equal((await data(await request("/api/store/orders", { cookie: accountCookie }))).some((order) => order.id === checked.order.id), true);
  assert.deepEqual((await data(await request(`/api/store/orders/${checked.order.id}/prescription`, { cookie: accountCookie }))).confirmedData, prescription);
  const simultaneous = await Promise.all(Array.from({ length: 12 }, () => request(`/api/store/orders/${checked.order.id}/prescription`, { cookie: accountCookie })));
  assert.deepEqual(simultaneous.map((response) => response.status), Array(12).fill(200));
});

test("HTTP rechaza archivos falsos o demasiado grandes antes de guardar", async () => {
  const guest = await cart();
  assert.equal((await upload(guest.cookie, Buffer.from("texto"), "text/plain")).status, 400);
  assert.equal((await upload(guest.cookie, Buffer.from("falso PNG"))).status, 400);
  assert.equal((await upload(guest.cookie, Buffer.alloc(4 * 1024 * 1024 + 1))).status, 400);
  assert.equal((await upload((await cart()).cookie, Buffer.alloc(4 * 1024 * 1024 + 128 * 1024 + 1))).status, 413);
  assert.equal(await db.external_prescriptions.count({ where: { cart_id: guest.cart.id } }), 0);
});

test("Cloudinary real: carga privada, recuperación, respaldo manual, reemplazo y consulta después de comprar", { skip: process.env.PRESCRIPTION_LIVE_STORAGE !== "true" }, async () => {
  const guest = await cart(); await addItems(guest.cookie);
  const uploaded = await data(await upload(guest.cookie));
  const id = uploaded.externalPrescription.id;
  const row = await db.external_prescriptions.findUniqueOrThrow({ where: { id } });
  assert.equal(row.file_data, null); assert.ok(row.cloudinary_asset_id);
  assert.equal(row.file_sha256, createHash("sha256").update(image).digest("hex"));
  const file = await request("/api/store/cart/prescription/image", { cookie: guest.cookie });
  assert.equal(file.status, 200); assert.match(file.headers.get("cache-control"), /private/);
  assert.equal(Buffer.from(await file.arrayBuffer()).subarray(1, 4).toString(), "PNG");
  assert.equal((await request("/api/store/cart/prescription/image")).status, 404);
  const unsigned = cloudinary.url(row.cloudinary_public_id, { cloud_name: process.env.CLOUDINARY_CLOUD_NAME, type: "authenticated", version: Number(row.cloudinary_version), format: row.cloudinary_format, secure: true, sign_url: false });
  assert.equal((await fetch(unsigned)).ok, false, "El original privado no debe ser accesible sin firma");
  assert.equal((await request("/api/store/cart/prescription/extract", { cookie: guest.cookie, method: "POST" })).status, 503);
  assert.equal((await db.external_prescriptions.findUniqueOrThrow({ where: { id } })).extraction_status, "FAILED");
  const confirmed = await data(await request("/api/store/cart/prescription/confirm", { cookie: guest.cookie, method: "PATCH", body: { ...prescription, imageHash: row.file_sha256 } }));
  assert.equal(confirmed.externalPrescription.status, "READY");
  assert.equal((await request("/api/store/cart/prescription/confirm", { cookie: guest.cookie, method: "PATCH", body: { ...prescription, imageHash: "a".repeat(64) } })).status, 404);
  const tokenHash = hashSessionToken(guest.cookie.split("=")[1]);
  const claimed = await claimCartPrescriptionExtraction(tokenHash, null, "TEST_PROVIDER");
  assert.equal(claimed.imageHash, row.file_sha256);
  const replacement = Buffer.concat([image, Buffer.from("synthetic-replacement")]);
  const replaced = await data(await upload(guest.cookie, replacement));
  const secondHash = replaced.externalPrescription.imageHash;
  assert.notEqual(secondHash, row.file_sha256);
  await claimCartPrescriptionExtraction(tokenHash, null, "TEST_PROVIDER");
  assert.ok((await completeCartPrescriptionExtraction(tokenHash, null, "TEST_PROVIDER", prescription, claimed.imageHash)).reason);
  await failCartPrescriptionExtraction(tokenHash, null, "TEST_PROVIDER", claimed.imageHash);
  assert.equal((await db.external_prescriptions.findUniqueOrThrow({ where: { id } })).extraction_status, "PENDING");
  await failCartPrescriptionExtraction(tokenHash, null, "TEST_PROVIDER", secondHash);
  await data(await request("/api/store/cart/prescription/confirm", { cookie: guest.cookie, method: "PATCH", body: { ...prescription, imageHash: secondHash } }));
  await configure(guest.cookie, { ...buyer, rut: fixtureRut(9303) });
  const order = await data(await request("/api/store/cart/checkout", { cookie: guest.cookie, method: "POST" }), 201);
  const orderFile = `/api/store/orders/${order.order.id}/prescription/file`;
  assert.equal((await request(orderFile, { cookie: guest.cookie })).status, 200);
  assert.equal((await request(orderFile)).status, 404);
  assert.equal((await request(`/api/external-prescriptions/${id}/file`, { cookie: await login() })).status, 200);
  assert.equal((await request(`/api/external-prescriptions/${id}/file`, { cookie: await login(true) })).status, 403);
  const removable = await cart(); const removableImage = await data(await upload(removable.cookie));
  await data(await request("/api/store/cart/prescription/image", { cookie: removable.cookie, method: "DELETE" }));
  assert.equal(await db.external_prescriptions.findUnique({ where: { id: removableImage.externalPrescription.id } }), null);
});
