export function getPermissionsForRoles(roleCodes) {
  const permissions = new Set();

  for (const roleCode of roleCodes) {
    for (const permission of ROLE_PERMISSIONS[roleCode] ?? []) {
      permissions.add(permission);
    }
  }

  return [...permissions];
}
